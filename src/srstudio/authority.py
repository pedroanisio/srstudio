"""Master/check-specific human dispositions (ADR 0246).

Message records are evidence supplied by the caller from its authoritative message
store, never generated by this gate. Structural validation does not authenticate a
Slack account; the caller must retain the exact source message and its identity.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from dataclasses import asdict, dataclass
from typing import Any

from .checks import number
from .errors import SrstudioError

SCOPES = (
    "production",
    "reserved",
    "rafa",
    "host",
    "new_pilot",
    "likeness",
    "sdk_main",
    "super_tools_main",
    "auto_enhance",
)


class AuthorityError(SrstudioError, ValueError):
    """Missing, stale, self-authored or mismatched authority evidence."""


@dataclass(frozen=True)
class Message:
    author: str
    reference: str
    text: str


@dataclass(frozen=True)
class Disposition:
    master_sha256: str
    check: str
    line: str | None
    reason: str
    bounds: tuple[float, float] | None
    scope: str
    requester: str
    message: Message
    exact_message: str

    def __post_init__(self) -> None:
        if not isinstance(self.master_sha256, str) or not re.fullmatch("[a-f0-9]{64}", self.master_sha256):
            raise AuthorityError("approval needs the final master sha256")
        if not isinstance(self.check, str) or not self.check.strip():
            raise AuthorityError("approval needs an exact check")
        if self.line is not None and (not isinstance(self.line, str) or not self.line.strip()):
            raise AuthorityError("approval line must be a nonempty line id or None")
        if not isinstance(self.reason, str) or not 3 <= len(self.reason.split()) or len(self.reason) > 200:
            raise AuthorityError("approval reason needs at least three words and at most 200 characters")
        if self.scope not in SCOPES:
            raise AuthorityError("approval needs an explicit production or reserved scope")
        if self.bounds is not None and not (
            isinstance(self.bounds, tuple)
            and len(self.bounds) == 2
            and all(number(v) for v in self.bounds)
            and 0 <= self.bounds[0] <= self.bounds[1]
        ):
            raise AuthorityError("approval bounds must be finite ordered nonnegative numbers")
        if not isinstance(self.message, Message):
            raise AuthorityError("approval needs the exact source message")
        if not all(
            isinstance(v, str) and v.strip()
            for v in (
                self.requester,
                self.message.author,
                self.message.reference,
                self.message.text,
                self.exact_message,
            )
        ):
            raise AuthorityError("approval needs requester, approver, evidence reference and exact message")
        if self.message.author.strip().casefold() == self.requester.strip().casefold():
            raise AuthorityError("self-authored approval is refused")
        if self.message.text != self.exact_message:
            raise AuthorityError("exact approval message does not match evidence")
        allowed = ("arc4d3", "Pedro") if self.scope == "production" else ("Pedro",)
        if self.message.author not in allowed:
            raise AuthorityError(f"{self.scope}: approval requires {' or '.join(allowed)}")

    def validate(
        self,
        master_sha256: str,
        check: str,
        line: str | None,
        reason: str,
        bounds: tuple[float, float] | None,
        scope: str,
    ) -> None:
        if (self.master_sha256, self.check, self.line, self.reason, self.bounds, self.scope) != (
            master_sha256,
            check,
            line,
            reason,
            bounds,
            scope,
        ):
            raise AuthorityError("stale or mismatched approval: master/check/line/reason/bounds/scope")

    def record(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def parse(cls, value: object) -> Disposition:
        if not isinstance(value, Mapping):
            raise AuthorityError("missing typed approval evidence")
        expected = set(cls.__dataclass_fields__)
        if set(value) != expected:
            raise AuthorityError("approval evidence fields are missing or unknown")
        msg = value["message"]
        if not isinstance(msg, Mapping) or set(msg) != {"author", "reference", "text"}:
            raise AuthorityError("approval needs source message author, reference and text")
        bounds = value["bounds"]
        if isinstance(bounds, list):
            if len(bounds) != 2:
                raise AuthorityError("approval bounds need two values")
            bounds = (bounds[0], bounds[1])
        return cls(**(dict(value) | {"message": Message(**msg), "bounds": bounds}))


def authorize(waiver: Mapping[str, Any], master_sha256: str, check: str, line: str | None, scope: str) -> Disposition:
    """Validate the complete proposal against the retained decision evidence."""
    from .direction import LINE_CHECKS, REEL_CHECKS, DirectionError, Waiver

    if check not in (REEL_CHECKS if line is None else LINE_CHECKS):
        raise AuthorityError("waiver check does not belong to this reel/line")
    bounds = waiver.get("bounds")
    if isinstance(bounds, list):
        bounds = tuple(bounds)
    proposed_check, reason = waiver.get("check"), waiver.get("reason")
    if not isinstance(proposed_check, str) or not isinstance(reason, str):
        raise AuthorityError("waiver needs a check and reason")
    try:
        proposal = Waiver(proposed_check, reason, bounds)
    except (DirectionError, TypeError) as exc:
        raise AuthorityError(str(exc)) from exc
    d = Disposition.parse(waiver.get("approval"))
    d.validate(master_sha256, check, line, proposal.reason, proposal.bounds, scope)
    if proposal.check != check:
        raise AuthorityError("waiver check does not match requested check")
    return d
